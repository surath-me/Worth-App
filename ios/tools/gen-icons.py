#!/usr/bin/env python3
"""Copy the web app's icons (index.html: MI paths + ICONS picker order) into the native app as
ios/Worth/Model/MaterialIcons.swift, so both apps draw exactly the same Material Symbols.
Run from the repo root after changing icons in index.html:  python3 ios/tools/gen-icons.py"""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
html = (root / "index.html").read_text()
paths = {}
a = html.index("const MI = {"); b = html.index("\n};", a)
for k, v in re.findall(r'"([a-zA-Z0-9_]+)":"([^"]+)"', html[a:b]): paths[k] = v
a = html.index("Object.assign(MI, {"); b = html.index("\n});", a)
for k, v in re.findall(r'"([a-zA-Z0-9_]+)":"([^"]+)"', html[a:b]): paths[k] = v
icons = json.loads(re.search(r"const ICONS = (\[[^\]]*\]);", html).group(1))
lines = ["// Generated by ios/tools/gen-icons.py from index.html. Do not edit by hand.", "", "enum MaterialIcons {",
         "    /// Material Symbols Rounded path data (viewBox 0 -960 960 960), keyed like the web app's MI.",
         "    static let paths: [String: String] = ["]
lines += [f'        "{k}": "{v}",' for k, v in sorted(paths.items())]
lines += ["    ]", "    /// The icons an entry can pick, in the web app's picker order (ICONS).", "    static let picker: [String] = ["]
lines += ["        " + ", ".join(json.dumps(k) for k in icons[i:i + 6]) + "," for i in range(0, len(icons), 6)]
lines += ["    ]", "}", ""]
out = root / "ios/Worth/Model/MaterialIcons.swift"
out.write_text("\n".join(lines))
print(f"{len(paths)} icons, {len(icons)} in the picker -> {out.relative_to(root)}")
